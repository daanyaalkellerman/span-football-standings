    @Test void historicalInputMatchesEveryReferenceRowAndCliOutput() throws Exception {
        Path input = Path.of("data/results.csv");
        byte[] original = Files.readAllBytes(input);
        var matches = Csv.read(input);
        assertEquals(107, matches.size());
        var rows = Standings.calculate(matches);
        assertEquals(22, rows.size());
        assertEquals(List.of("Ipswich Town", "Manchester City", "Liverpool"), rows.subList(0, 3).stream().map(r -> r.team().name()).toList());
        assertEquals(List.of(16L, 14L, 13L), rows.subList(0, 3).stream().map(r -> r.team().points()).toList());
        assertEquals(214, rows.stream().mapToLong(r -> r.team().played()).sum());
        assertEquals(214, rows.stream().mapToLong(r -> r.team().points()).sum());
        assertEquals(288, rows.stream().mapToLong(r -> r.team().goalsFor()).sum());
        assertEquals(288, rows.stream().mapToLong(r -> r.team().goalsAgainst()).sum());
        assertEquals(rows.stream().mapToLong(r -> r.team().won()).sum(), rows.stream().mapToLong(r -> r.team().lost()).sum());
        assertEquals(6, rows.stream().filter(r -> r.team().played() == 9).count());
        assertEquals(16, rows.stream().filter(r -> r.team().played() == 10).count());
        for (var row : rows) assertEquals(row.team().played(), row.team().won() + row.team().drawn() + row.team().lost());
        Path output = directory.resolve("standings.csv");
        assertEquals(0, Main.run(new String[]{input.toString(), output.toString()}, System.err));
        assertEquals(EXPECTED, Files.readString(output));
        assertArrayEquals(original, Files.readAllBytes(input));
    }
